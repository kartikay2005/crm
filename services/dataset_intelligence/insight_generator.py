"""
Dataset Intelligence Engine — Step 13: Automatic Insight Generator.

Builds plain-English findings from data already computed by Segments 1-4 —
no new expensive computation, just interpretation. Every insight is
generated by a deterministic rule (correlation strength, outlier
percentage, class imbalance, quality notes, prediction distribution), so
this stays explainable and testable; there's no black-box summarization
step required to make it work.

LLM polish is optional and additive: `generate_insights` always produces
correct, if plainly-worded, template text first, then — only if
`enable_llm_features` is on and a key is configured — attempts to rewrite
the phrasing more naturally, falling back to the template on any failure
(timeout, API error, malformed response). The insight *content* never
depends on the LLM being available; only the wording might improve.
"""
from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np
import pandas as pd

from core.config import get_settings
from core.logging_config import get_logger
from services.dataset_intelligence.prediction import PredictionResult
from services.dataset_intelligence.profiler import DatasetProfile
from services.dataset_intelligence.quality_readiness import ScoreBreakdown

_log = get_logger(__name__)

VALID_CATEGORIES = {"trend", "correlation", "risk", "anomaly", "summary"}
VALID_SEVERITIES = {"info", "warning", "critical"}


@dataclass
class Insight:
    category: str
    text: str
    severity: str = "info"
    supporting_data: dict = field(default_factory=dict)


@dataclass
class InsightBundle:
    summary: str
    key_findings: list[Insight] = field(default_factory=list)
    risks: list[Insight] = field(default_factory=list)
    hidden_trends: list[Insight] = field(default_factory=list)
    anomalies: list[Insight] = field(default_factory=list)


# ---------------------------------------------------------------------------
# Individual rule-based generators — each returns [] rather than raising if
# its precondition isn't met (no datetime column, no imbalance, etc). This
# mirrors the fallback-friendly design used throughout the pipeline: an
# insight category just being empty is a normal outcome, not an error.
# ---------------------------------------------------------------------------
def _correlation_insights(profile: DatasetProfile) -> list[Insight]:
    if not profile.correlation_matrix:
        return []
    seen: set[frozenset] = set()
    insights = []
    cols = list(profile.correlation_matrix.keys())
    for a in cols:
        for b in cols:
            if a == b:
                continue
            pair = frozenset((a, b))
            if pair in seen:
                continue
            corr = profile.correlation_matrix[a].get(b)
            if corr is None or abs(corr) < 0.7:
                continue
            seen.add(pair)
            direction = "positively" if corr > 0 else "negatively"
            insights.append(Insight(
                category="correlation",
                text=f"{a} and {b} are strongly {direction} correlated (r={corr:.2f}).",
                severity="info",
                supporting_data={"column_a": a, "column_b": b, "correlation": corr},
            ))
    return insights


def _outlier_insights(profile: DatasetProfile) -> list[Insight]:
    insights = []
    for col in profile.columns:
        if col.outlier_pct is not None and col.outlier_pct > 15.0:
            insights.append(Insight(
                category="anomaly",
                text=f"'{col.name}' has an unusually high proportion of outliers "
                     f"({col.outlier_pct:.1f}% of values, by IQR method).",
                severity="warning",
                supporting_data={"column": col.name, "outlier_pct": col.outlier_pct},
            ))
    return insights


def _imbalance_insights(profile: DatasetProfile) -> list[Insight]:
    if not profile.class_imbalance or not profile.class_imbalance.get("is_imbalanced"):
        return []
    ci = profile.class_imbalance
    return [Insight(
        category="risk",
        text=f"Target candidate '{ci['column']}' is imbalanced — the majority class "
             f"makes up {ci['majority_class_pct']:.1f}% of rows. Predictions and "
             f"accuracy metrics on this column should be interpreted with that in mind.",
        severity="warning",
        supporting_data=ci,
    )]


def _quality_insights(quality: ScoreBreakdown) -> list[Insight]:
    severity = "critical" if quality.score < 50 else "warning" if quality.score < 70 else "info"
    return [
        Insight(category="risk", text=note, severity=severity, supporting_data={})
        for note in quality.notes
    ]


def _trend_insights(df: pd.DataFrame, profile: DatasetProfile) -> list[Insight]:
    if not profile.datetime_columns or not profile.numerical_columns:
        return []
    date_col = profile.datetime_columns[0]
    working = df[[date_col] + profile.numerical_columns].dropna(subset=[date_col]).sort_values(date_col)
    if len(working) < 5:
        return []

    x = pd.to_numeric(working[date_col]).to_numpy(dtype=float)
    x = (x - x.min()) / (x.max() - x.min() + 1e-9)  # normalize to [0,1] for stable slope scale

    insights = []
    for col in profile.numerical_columns:
        y = pd.to_numeric(working[col], errors="coerce")
        valid = y.notna()
        if valid.sum() < 5:
            continue
        slope, _ = np.polyfit(x[valid.to_numpy()], y[valid].to_numpy(), 1)
        mean_val = float(y[valid].mean())
        if mean_val == 0:
            continue
        relative_change = abs(slope) / abs(mean_val)
        if relative_change < 0.15:
            continue  # not a meaningful trend, don't force a narrative
        direction = "increasing" if slope > 0 else "decreasing"
        insights.append(Insight(
            category="trend",
            text=f"'{col}' shows a {direction} trend over '{date_col}'.",
            severity="info",
            supporting_data={"column": col, "date_column": date_col, "slope": float(slope)},
        ))
    return insights


def _prediction_insights(prediction: PredictionResult | None) -> list[Insight]:
    if prediction is None:
        return []
    dist = prediction.prediction_distribution
    if prediction.problem_type == "regression":
        return [Insight(
            category="summary",
            text=f"Predicted {prediction.target_variable} ranges from {dist['min']:.1f} to "
                 f"{dist['max']:.1f}, averaging {dist['mean']:.1f} across {prediction.n_rows_predicted} rows.",
            severity="info", supporting_data=dist,
        )]
    total = sum(dist.values()) or 1
    parts = [f"{100 * v / total:.0f}% predicted '{k}'" for k, v in dist.items()]
    return [Insight(
        category="summary",
        text=f"For {prediction.target_variable}: " + ", ".join(parts) +
             f" (across {prediction.n_rows_predicted} rows).",
        severity="info", supporting_data=dist,
    )]


# ---------------------------------------------------------------------------
# Optional LLM polish — additive only, never load-bearing for correctness
# ---------------------------------------------------------------------------
def _llm_polish(insights: list[Insight]) -> list[Insight]:
    settings = get_settings()
    if not settings.enable_llm_features or not settings.openai_api_key:
        return insights
    try:
        import httpx
        texts = [i.text for i in insights]
        prompt = (
            "Rewrite each of these data-analysis findings to sound more natural and "
            "conversational, keeping every number and fact exactly as given. Return "
            "one rewritten line per input line, same order, no extra commentary:\n\n"
            + "\n".join(f"{i+1}. {t}" for i, t in enumerate(texts))
        )
        resp = httpx.post(
            "https://api.openai.com/v1/chat/completions",
            headers={"Authorization": f"Bearer {settings.openai_api_key.get_secret_value()}"},
            json={
                "model": settings.openai_model,
                "messages": [{"role": "user", "content": prompt}],
                "max_tokens": 1000,
            },
            timeout=settings.llm_request_timeout_seconds,
        )
        resp.raise_for_status()
        content = resp.json()["choices"][0]["message"]["content"]
        lines = [l.split(".", 1)[-1].strip() for l in content.strip().split("\n") if l.strip()]
        if len(lines) != len(insights):
            return insights  # malformed response — don't risk mismatched rewrites
        for insight, new_text in zip(insights, lines):
            insight.text = new_text
        return insights
    except Exception as exc:  # noqa: BLE001
        _log.warning("insights.llm_polish_failed", error=str(exc))
        return insights  # template text is always correct; polish is best-effort only


# ---------------------------------------------------------------------------
# Orchestrator
# ---------------------------------------------------------------------------
def generate_insights(
    df: pd.DataFrame, profile: DatasetProfile, domain_result, quality: ScoreBreakdown,
    readiness: ScoreBreakdown, prediction: PredictionResult | None,
) -> InsightBundle:
    all_insights: list[Insight] = []
    all_insights += _correlation_insights(profile)
    all_insights += _outlier_insights(profile)
    all_insights += _imbalance_insights(profile)
    all_insights += _quality_insights(quality)
    all_insights += _trend_insights(df, profile)
    all_insights += _prediction_insights(prediction)

    all_insights = _llm_polish(all_insights)

    key_findings = [i for i in all_insights if i.category in ("correlation", "summary")]
    risks = [i for i in all_insights if i.category == "risk"]
    hidden_trends = [i for i in all_insights if i.category == "trend"]
    anomalies = [i for i in all_insights if i.category == "anomaly"]

    # Build a short summary from the highest-severity items first, capped
    # at 3 sentences so it stays skimmable.
    by_severity = sorted(all_insights, key=lambda i: {"critical": 0, "warning": 1, "info": 2}[i.severity])
    if by_severity:
        summary = " ".join(i.text for i in by_severity[:3])
    else:
        summary = (
            f"This dataset ({profile.n_rows} rows, {profile.n_columns} columns) shows no "
            f"strong correlations, outliers, or imbalance signals worth flagging."
        )

    return InsightBundle(
        summary=summary, key_findings=key_findings, risks=risks,
        hidden_trends=hidden_trends, anomalies=anomalies,
    )
